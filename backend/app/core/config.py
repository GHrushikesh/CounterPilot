import json
from typing import List, Union, Optional
from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    PROJECT_NAME: str = "CounterPilot"
    ENVIRONMENT: str = "development"
    API_PREFIX: str = "/api"
    DATABASE_URL: str = "sqlite:///./counterpilot.db"
    CORS_ORIGINS: Union[List[str], str] = [
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "http://localhost:3000",
    ]

    # BharatCode Model API Configuration
    BHARATCODE_API_KEY: Optional[str] = None
    BHARATCODE_API_BASE_URL: str = "https://bharatcode.ai/api/model/v1"
    BHARATCODE_MODEL: str = "qwen-3.8-27b"
    BHARATCODE_TIMEOUT_SECONDS: float = 30.0

    @field_validator("CORS_ORIGINS", mode="before")
    @classmethod
    def assemble_cors_origins(cls, v: Union[str, List[str]]) -> List[str]:
        if isinstance(v, str):
            v_trimmed = v.strip()
            if v_trimmed.startswith("[") and v_trimmed.endswith("]"):
                try:
                    return json.loads(v_trimmed)
                except Exception:
                    pass
            return [i.strip() for i in v_trimmed.split(",") if i.strip()]
        elif isinstance(v, list):
            return v
        return ["*"]

    model_config = SettingsConfigDict(
        env_file=(".env", "backend/.env", "../.env"),
        env_file_encoding="utf-8",
        extra="ignore"
    )


settings = Settings()

